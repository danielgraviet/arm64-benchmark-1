#!/usr/bin/env bash
# Harness-only bring-up for an already-live phoenix-e6 cell.
# Never apt, never reseed regions, never overwrite eng binaries.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PHOENIX_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
ROOT="$(cd "${PHOENIX_DIR}/.." && pwd)"
cd "${ROOT}"

export PATH="${HOME}/.local/bin:/usr/local/bin:${PATH}"
export UV_NO_SYNC=1

log() { printf '[phoenix-e6] %s\n' "$*"; }
die() { printf '[phoenix-e6] ERROR: %s\n' "$*" >&2; exit 1; }

[[ "$(uname -m)" == "x86_64" ]] || die "expected x86_64"
[[ -e /dev/kvm ]] || die "/dev/kvm missing"
curl -fsS -m 5 http://127.0.0.1:8088/health >/dev/null \
  || die "API health failed — eng cell must already be up"

if [[ -f "${ROOT}/.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "${ROOT}/.env"
  set +a
fi
[[ -n "${RLP_API_KEY:-}" ]] || die "RLP_API_KEY missing in .env"

# Pin client env to localhost + this region (do not invent a new key).
key="${RLP_API_KEY}"
cat > "${ROOT}/.env" <<EOF
# Generated by phoenix-e6/scripts/start.sh — never commit.

RLP_API_URL=http://127.0.0.1:8088
RLP_TOOLBOX_URL=http://127.0.0.1:9000/toolbox
RLP_API_KEY=${key}
RLP_HTTP_MAX_CONNECTIONS=8192

PHOENIX_E6_RLP_API_URL=http://127.0.0.1:8088
PHOENIX_E6_RLP_TOOLBOX_URL=http://127.0.0.1:9000/toolbox
PHOENIX_E6_RLP_API_KEY=${key}
EOF
chmod 600 "${ROOT}/.env"

log "uv sync + eng rlp-sdk (harness only)"
if command -v uv >/dev/null 2>&1; then
  uv python install 3.13 >/dev/null 2>&1 || true
  uv sync
  bash "${ROOT}/scripts/host/install_eng_rlp_sdk.sh"
else
  die "uv missing on PATH — install uv, then re-run ./o start"
fi

if ! UV_NO_SYNC=1 uv run python -c 'from rlp import Resources; assert "cpu_max" in Resources.__dataclass_fields__'; then
  die "eng rlp-sdk missing cpu_max after install"
fi

log "harness ready (target=phoenix-e6). Next: ./o hw && ./o pin && ./o test"
